// Clean code function
function cleanCode(code: string, removeAllComments: boolean = false): string {
  if (!code) return ""
  const lines = code.split('\n')
  const cleanedLines = lines.filter(line => {
    const trimmed = line.trim()
    if (removeAllComments) {
      if (trimmed.startsWith('#')) return false
    } else {
      if (trimmed.startsWith('#') && (
        trimmed.includes('AuraFX') || trimmed.includes('discord.gg') ||
        trimmed.includes('Generated by') || trimmed.includes('Visit') || trimmed.includes('Support')
      )) return false
    }
    return true
  })
  return cleanedLines.join('\n')
}

// Virtual Scrolling Code Display Component
function CompactCodeDisplay({ code, isVisible }: { code: string; isVisible: boolean }) {
  const cleanedCode = useMemo(() => cleanCode(code, true), [code])
  const allLines = useMemo(() => cleanedCode.split("\n").filter(line => line.trim()), [cleanedCode])

  const [scrollTop, setScrollTop] = useState(0)
  const containerRef = useRef<HTMLDivElement>(null)

  const LINE_HEIGHT = 16
  const CONTAINER_HEIGHT = 280
  const VISIBLE_LINES = Math.ceil(CONTAINER_HEIGHT / LINE_HEIGHT)
  const BUFFER_SIZE = 10

  const startIndex = Math.max(0, Math.floor(scrollTop / LINE_HEIGHT) - BUFFER_SIZE)
  const endIndex = Math.min(allLines.length, startIndex + VISIBLE_LINES + (BUFFER_SIZE * 2))
  const visibleLines = allLines.slice(startIndex, endIndex)
  const totalHeight = allLines.length * LINE_HEIGHT

  const handleScroll = (e: React.UIEvent<HTMLDivElement>) => {
    setScrollTop(e.currentTarget.scrollTop)
  }

  if (!isVisible) {
    return (
      <div className="h-72 flex items-center justify-center border border-dashed border-border/50 rounded-xl bg-muted/5">
        <div className="text-center space-y-1">
          <EyeOff className="w-6 h-6 text-muted-foreground mx-auto" />
          <p className="text-[10px] uppercase tracking-widest text-muted-foreground font-bold">Preview hidden</p>
        </div>
      </div>
    )
  }

  return (
    <div className="h-72 flex flex-col bg-card rounded-xl border border-border/50 overflow-hidden">
      {/* Header */}
      <div className="flex-shrink-0 px-3 py-2 bg-muted/30 border-b border-border/50 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <div className="flex gap-1">
            <div className="w-2 h-2 rounded-full bg-muted-foreground/30" />
            <div className="w-2 h-2 rounded-full bg-muted-foreground/30" />
            <div className="w-2 h-2 rounded-full bg-muted-foreground/30" />
          </div>
          <span className="text-[10px] font-mono text-muted-foreground uppercase tracking-wider">effect.yaml</span>
        </div>
        <span className="text-[10px] text-muted-foreground font-mono">{allLines.length} lines</span>
      </div>

      {/* Virtual Scroll Code */}
      <div
        ref={containerRef}
        className="flex-1 overflow-auto custom-scrollbar"
        onScroll={handleScroll}
      >
        <div style={{ height: totalHeight, position: 'relative' }}>
          <div
            style={{ position: 'absolute', top: startIndex * LINE_HEIGHT, width: '100%' }}
            className="font-mono text-[10px] leading-tight min-w-max"
          >
            {visibleLines.map((line, index) => {
              const actualIndex = startIndex + index
              return (
                <div
                  key={actualIndex}
                  className="flex hover:bg-muted/30 transition-colors min-w-max"
                  style={{ height: LINE_HEIGHT }}
                >
                  <span className="flex-shrink-0 text-muted-foreground text-right px-2 py-0.5 select-none w-8 bg-muted/10">
                    {actualIndex + 1}
                  </span>
                  <span className="px-2 py-0.5 text-foreground/80 whitespace-nowrap">
                    {line || " "}
                  </span>
                </div>
              )
            })}
          </div>
        </div>
      </div>
    </div>
  )
}

export function CodePanel({
  code = "",
  onGenerateCode = async () => { },
  isGenerating = false,
  settings = {
    particleCount: 100, shapeSize: 1, color: "#ff6b35", particle: "reddust",
    alpha: 10, repeat: 1, yOffset: 0, skillName: "MyEffect", pngSize: 100,
    objScale: 1, performanceMode: false, imageColorMode: false,
    frameMode: "auto", frameCount: 60
  },
  onSettingsChange = () => { },
  modes = {
    rotateMode: false, rainbowMode: false, riseMode: false, performanceMode: false,
    localRotateMode: false, moveMode: false, proximityMode: false, staticRainbowMode: false
  },
  onFrameSettingsChange = () => { },
  optimize = false,
  setOptimize = () => { }
}: CodePanelProps) {
  const [copied, setCopied] = useState(false)
  const [showCode, setShowCode] = useState(true)
  const [settingsExpanded, setSettingsExpanded] = useState(true)
  const [framesExpanded, setFramesExpanded] = useState(true)
  const [codePreviewExpanded, setCodePreviewExpanded] = useState(true)
  const [frameMode, setFrameMode] = useState<"auto" | "manual">("auto")
  const [manualFrameCount, setManualFrameCount] = useState(120)
  const { toast } = useToast()

  const handleCopy = async () => {
    try {
      const cleanedCode = cleanCode(code, false)
      await navigator.clipboard.writeText(cleanedCode)
      setCopied(true)
      toast({ title: "Copied!", description: "Code copied to clipboard", duration: 2000 })
      setTimeout(() => setCopied(false), 2000)
    } catch (error) {
      toast({ title: "Error", description: "Failed to copy code", variant: "destructive", duration: 2000 })
    }
  }

  const handleDownload = () => {
    const cleanedCode = cleanCode(code, false)
    const blob = new Blob([cleanedCode], { type: "text/yaml" })
    const url = URL.createObjectURL(blob)
    const a = document.createElement("a")
    a.href = url
    a.download = `${settings.skillName || "effect"}.yaml`
    a.click()
    URL.revokeObjectURL(url)
    toast({ title: "Downloaded", description: `Effect saved as ${settings.skillName || "effect"}.yaml`, duration: 2000 })
  }

  const handleGenerate = async () => { await onGenerateCode(optimize) }

  const handleFrameModeChange = (mode: "auto" | "manual") => {
    setFrameMode(mode)
    onFrameSettingsChange(mode, mode === "manual" ? manualFrameCount : undefined)
  }

  const handleManualFrameChange = (value: number) => {
    setManualFrameCount(value)
    if (frameMode === "manual") onFrameSettingsChange("manual", value)
  }

  return (
    <div className="w-full h-full flex flex-col bg-transparent text-foreground overflow-hidden">
      {/* 1. Header */}
      <div className="flex items-center justify-between mb-6 flex-shrink-0 px-2 lg:px-0 mt-2">
        <div className="flex items-center gap-3">
          <div className="p-2 rounded-xl border bg-muted text-foreground border-border/50">
            <Code2 className="w-5 h-5 text-foreground" />
          </div>
          <div>
            <h3 className="font-bold text-base tracking-tight text-foreground">Code Generator</h3>
            <p className="text-[10px] uppercase tracking-wider text-muted-foreground font-semibold">MythicMobs YAML</p>
          </div>
        </div>
      </div>

      <div className="flex-1 overflow-y-auto pr-1 space-y-2 custom-scrollbar">

        {/* Generate Button */}
        <button
          onClick={handleGenerate}
          disabled={isGenerating}
          className="w-full p-3 rounded-xl border border-foreground bg-foreground text-background font-bold text-xs uppercase tracking-widest hover:opacity-90 disabled:opacity-50 transition-all flex items-center justify-center gap-2"
        >
          {isGenerating ? (
            <><Loader2 className="w-4 h-4 animate-spin" /> Generating...</>
          ) : (
            <><Zap className="w-4 h-4" /> Generate Code</>
          )}
        </button>

        {/* SECTION: SETTINGS */}
        <div className="bg-card border border-border/50 rounded-xl overflow-hidden">
          <button
            onClick={() => setSettingsExpanded(!settingsExpanded)}
            className="w-full flex items-center justify-between p-3 hover:bg-muted/30 transition-colors"
          >
            <div className="flex items-center gap-2">
              <Settings className="w-4 h-4 text-muted-foreground" />
              <span className="text-[11px] font-bold uppercase tracking-wider flex-1 text-left text-foreground">Settings</span>
            </div>
            {settingsExpanded ? <ChevronUp className="w-3.5 h-3.5 text-muted-foreground" /> : <ChevronDown className="w-3.5 h-3.5 text-muted-foreground" />}
          </button>

          <AnimatePresence>
            {settingsExpanded && (
              <motion.div
                initial={{ height: 0, opacity: 0 }}
                animate={{ height: "auto", opacity: 1 }}
                exit={{ height: 0, opacity: 0 }}
                transition={{ duration: 0.2, ease: "easeInOut" }}
                className="overflow-hidden bg-muted/10 border-t border-border/50"
              >
                <div className="p-3 space-y-4">
                  {/* Skill Name */}
                  <div>
                    <label className="text-[10px] font-bold uppercase block text-foreground mb-1.5">Skill Name</label>
                    <Input
                      type="text"
                      value={settings.skillName}
                      onChange={(e) => onSettingsChange({ ...settings, skillName: e.target.value })}
                      placeholder="Enter effect name..."
                      className="bg-card border-border/50 text-foreground text-xs h-8 rounded-lg focus-visible:ring-1 focus-visible:ring-foreground"
                    />
                  </div>

                  {/* Optimize Code Toggle */}
                  <div className="flex items-center justify-between p-2.5 bg-card border border-border/50 rounded-xl h-10">
                    <span className="text-[10px] font-bold uppercase text-foreground">Optimize Code</span>
                    <Switch
                      checked={optimize}
                      onCheckedChange={(v: boolean) => setOptimize(v)}
                      className="scale-[0.8] origin-right"
                    />
                  </div>

                  {/* Player Relative Offsets */}
                  <div className="flex items-center justify-between p-2.5 bg-card border border-border/50 rounded-xl">
                    <div className="flex flex-col">
                      <span className="text-[10px] font-bold uppercase text-foreground">Player Relative</span>
                      <span className="text-[8px] text-muted-foreground uppercase tracking-widest">Rotate with player (fo/so/uo)</span>
                    </div>
                    <Switch
                      checked={settings.useRelativeOffsets ?? true}
                      onCheckedChange={(v: boolean) => onSettingsChange({ ...settings, useRelativeOffsets: v })}
                      className="scale-[0.8] origin-right"
                    />
                  </div>
                </div>
              </motion.div>
            )}
          </AnimatePresence>
        </div>

        {/* SECTION: ANIMATION FRAMES */}
        <div className="bg-card border border-border/50 rounded-xl overflow-hidden">
          <button
            onClick={() => setFramesExpanded(!framesExpanded)}
            className="w-full flex items-center justify-between p-3 hover:bg-muted/30 transition-colors"
          >
            <div className="flex items-center gap-2">
              <Film className="w-4 h-4 text-muted-foreground" />
              <span className="text-[11px] font-bold uppercase tracking-wider flex-1 text-left text-foreground">Animation Frames</span>
            </div>
            {framesExpanded ? <ChevronUp className="w-3.5 h-3.5 text-muted-foreground" /> : <ChevronDown className="w-3.5 h-3.5 text-muted-foreground" />}
          </button>

          <AnimatePresence>
            {framesExpanded && (
              <motion.div
                initial={{ height: 0, opacity: 0 }}
                animate={{ height: "auto", opacity: 1 }}
                exit={{ height: 0, opacity: 0 }}
                transition={{ duration: 0.2, ease: "easeInOut" }}
                className="overflow-hidden bg-muted/10 border-t border-border/50"
              >
                <div className="p-3 space-y-4">
                  {/* Frame Mode Toggle */}
                  <div className="space-y-2">
                    <label className="text-[10px] font-bold uppercase block text-foreground">Frame Mode</label>
                    <div className="flex gap-1 bg-muted/30 rounded-xl p-1 border border-border/50">
                      <button
                        onClick={() => handleFrameModeChange("auto")}
                        className={`flex-1 py-2 px-3 text-[10px] font-bold uppercase tracking-widest rounded-lg transition-all ${
                          frameMode === "auto"
                            ? "bg-foreground text-background shadow-sm"
                            : "text-muted-foreground hover:text-foreground"
                        }`}
                      >Auto</button>
                      <button
                        onClick={() => handleFrameModeChange("manual")}
                        className={`flex-1 py-2 px-3 text-[10px] font-bold uppercase tracking-widest rounded-lg transition-all ${
                          frameMode === "manual"
                            ? "bg-foreground text-background shadow-sm"
                            : "text-muted-foreground hover:text-foreground"
                        }`}
                      >Manual</button>
                    </div>
                  </div>

                  {/* Manual Frame Count */}
                  <AnimatePresence>
                    {frameMode === "manual" && (
                      <motion.div
                        initial={{ opacity: 0, height: 0 }}
                        animate={{ opacity: 1, height: "auto" }}
                        exit={{ opacity: 0, height: 0 }}
                        transition={{ duration: 0.2 }}
                        className="pl-3 border-l-2 border-foreground/20 space-y-2"
                      >
                        <div className="flex items-center justify-between">
                          <label className="text-[10px] font-bold uppercase text-foreground">Frame Count</label>
                          <span className="text-[10px] bg-muted text-foreground px-2 py-1 rounded font-mono">
                            {manualFrameCount}
                          </span>
                        </div>
                        <input
                          type="range"
                          min={12} max={240} step={6}
                          value={manualFrameCount}
                          onChange={(e) => handleManualFrameChange(Number(e.target.value))}
                          className="w-full h-1.5 bg-muted rounded-full appearance-none cursor-pointer slider"
                        />
                        <div className="flex justify-between text-[8px] text-muted-foreground uppercase tracking-widest">
                          <span>12</span>
                          <span>240</span>
                        </div>
                      </motion.div>
                    )}
                  </AnimatePresence>
                </div>
              </motion.div>
            )}
          </AnimatePresence>
        </div>

        {/* SECTION: CODE PREVIEW */}
        <div className="bg-card border border-border/50 rounded-xl overflow-hidden">
          <button
            onClick={() => setCodePreviewExpanded(!codePreviewExpanded)}
            className="w-full flex items-center justify-between p-3 hover:bg-muted/30 transition-colors"
          >
            <div className="flex items-center gap-2">
              <FileCode className="w-4 h-4 text-muted-foreground" />
              <span className="text-[11px] font-bold uppercase tracking-wider flex-1 text-left text-foreground">Code Preview</span>
            </div>
            {codePreviewExpanded ? <ChevronUp className="w-3.5 h-3.5 text-muted-foreground" /> : <ChevronDown className="w-3.5 h-3.5 text-muted-foreground" />}
          </button>

          <AnimatePresence>
            {codePreviewExpanded && (
              <motion.div
                initial={{ height: 0, opacity: 0 }}
                animate={{ height: "auto", opacity: 1 }}
                exit={{ height: 0, opacity: 0 }}
                transition={{ duration: 0.2, ease: "easeInOut" }}
                className="overflow-hidden bg-muted/10 border-t border-border/50"
              >
                <div className="p-3 space-y-3">
                  {/* Action Buttons */}
                  <div className="flex gap-2">
                    <button
                      onClick={() => setShowCode(!showCode)}
                      className={`flex-1 py-2 px-2 text-[10px] font-bold uppercase tracking-widest rounded-xl transition-all flex items-center justify-center gap-1.5 border ${
                        showCode
                          ? "bg-foreground text-background border-foreground"
                          : "bg-card text-muted-foreground border-border/50 hover:text-foreground hover:border-foreground/30"
                      }`}
                    >
                      {showCode ? <Eye className="w-3 h-3" /> : <EyeOff className="w-3 h-3" />}
                      {showCode ? "Hide" : "Show"}
                    </button>

                    <button
                      onClick={handleCopy}
                      disabled={!code || isGenerating}
                      className="flex-1 py-2 px-2 text-[10px] font-bold uppercase tracking-widest rounded-xl transition-all flex items-center justify-center gap-1.5 bg-card text-muted-foreground border border-border/50 hover:text-foreground hover:border-foreground/30 disabled:opacity-40"
                    >
                      {copied ? <Check className="w-3 h-3 text-foreground" /> : <Copy className="w-3 h-3" />}
                      Copy
                    </button>

                    <button
                      onClick={handleDownload}
                      disabled={!code || isGenerating}
                      className="flex-1 py-2 px-2 text-[10px] font-bold uppercase tracking-widest rounded-xl transition-all flex items-center justify-center gap-1.5 bg-card text-muted-foreground border border-border/50 hover:text-foreground hover:border-foreground/30 disabled:opacity-40"
                    >
                      <Download className="w-3 h-3" />
                      Save
                    </button>
                  </div>

                  {/* Code Display */}
                  <CompactCodeDisplay code={code} isVisible={showCode} />
                </div>
              </motion.div>
            )}
          </AnimatePresence>
        </div>
      </div>

      <style jsx global>{`
        .custom-scrollbar::-webkit-scrollbar { width: 3px; }
        .custom-scrollbar::-webkit-scrollbar-track { background: transparent; }
        .custom-scrollbar::-webkit-scrollbar-thumb { background: hsl(var(--border)); border-radius: 10px; }
        
        input[type="range"].slider::-webkit-slider-thumb {
          appearance: none;
          height: 12px;
          width: 12px;
          border-radius: 50%;
          background: hsl(var(--foreground));
          cursor: pointer;
          border: 2px solid hsl(var(--background));
          box-shadow: 0 0 0 1px hsl(var(--border));
        }
        input[type="range"].slider::-moz-range-thumb {
          height: 12px;
          width: 12px;
          border-radius: 50%;
          background: hsl(var(--foreground));
          cursor: pointer;
          border: 2px solid hsl(var(--background));
          box-shadow: 0 0 0 1px hsl(var(--border));
        }
      `}</style>
    </div>
  )
}